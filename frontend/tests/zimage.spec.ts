import { test, expect } from '@playwright/test'

test('H3 image has its own sizes and sampling, completes and preserves video edits on switching', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '创作工作台' })).toBeVisible()
  await page.getByLabel('当前账号', { exact: true }).selectOption('colab2')
  await page.getByLabel('画面描述', { exact: true }).fill('保留的视频提示词')
  await page.getByRole('button', { name: '图片', exact: true }).click()
  await expect(page.getByLabel('画面描述', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('帧数', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('采样步数', { exact: true })).toHaveValue('6')
  await expect(page.getByLabel('画面宽度')).toHaveValue('2048')
  await page.getByLabel('尺寸预设').selectOption('4096x4096')
  await expect(page.getByLabel('画面高度')).toHaveValue('4096')
  await page.getByLabel('画面描述', { exact: true }).fill('温暖阳光下的红色陶瓷杯，木纹清晰，写实摄影')
  await page.getByLabel('随机种子', { exact: true }).fill('1234')
  await page.getByRole('button', { name: '视频', exact: true }).click()
  await expect(page.getByLabel('画面描述', { exact: true })).toHaveValue('保留的视频提示词')
  await page.getByRole('button', { name: '图片', exact: true }).click()
  await expect(page.getByLabel('随机种子', { exact: true })).toHaveValue('1234')
  const submitted = page.waitForRequest(r => r.url().endsWith('/api/jobs') && r.method() === 'POST')
  await page.getByRole('button', { name: '生成图片' }).click()
  const body = (await submitted).postDataJSON()
  expect(Object.values(body.graph).some((n: any) => n.class_type === 'MiniMaxH3ImageConditioning')).toBeTruthy()
  expect(Object.values(body.graph).some((n: any) => n.class_type === 'CreateVideo')).toBeFalsy()
  await expect(page.getByAltText('生成结果')).toBeVisible({ timeout: 30000 })
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBe(720)
  await page.screenshot({ path: '../screenshots/review/h3-image-workbench.png' })
})
