test('settings dialog preserves the workspace and supports save, cancellation, errors and account switching', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '创作工作台' })).toBeVisible()
  await page.getByRole('button', {name:'创作参数',exact:true}).click()
  await page.getByLabel('项目名称', {exact:true}).fill('设置不打断创作')
  await page.getByLabel('画面描述', {exact:true}).fill('A fox crossing the snow.')
  const initial = (await (await page.request.get('/api/state')).json()).settings
  const trigger = page.getByRole('button', {name:'工作台设置',exact:true})
  const dialog = page.getByRole('dialog', {name:'工作台设置',exact:true})
  const save = dialog.getByRole('button', {name:'保存设置',exact:true})
  const idle = dialog.getByLabel('空闲自动关闭', {exact:true})
  const exitSwitch = dialog.getByRole('switch', {name:'退出时释放机器'})
  const identity = dialog.getByLabel('SSH 私钥路径', {exact:true})

  await trigger.click()
  await expect(dialog).toBeVisible()
  await expect(save).toBeDisabled()
  await dialog.getByRole('button', {name:'切换到 colab2',exact:true}).click()
  await expect(save).toBeEnabled()
  await expect(page.locator('.account-field select')).toHaveValue('colab2')
  expect(await page.evaluate(() => localStorage.getItem('fieldwork-account'))).toBe('colab2')
  await page.route('**/api/settings', route => route.fulfill({status:500,body:'Account-only confirmation must not write settings'}))
  await save.click()
  await expect(dialog).toHaveCount(0)
  await page.unroute('**/api/settings')
  expect((await (await page.request.get('/api/state')).json()).settings).toEqual(initial)
  await trigger.click()
  await expect(save).toBeDisabled()
  await expect(identity).toBeHidden()
  await idle.selectOption('60')
  await exitSwitch.focus()
  await page.keyboard.press('Space')
  expect(await exitSwitch.isChecked()).toBe(!initial.stop_on_exit)
  await dialog.getByText('高级连接', {exact:true}).click()
  await identity.fill('/tmp/workbench-test-identity')
  await dialog.getByRole('button', {name:'取消',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page.getByLabel('项目名称', {exact:true})).toHaveValue('设置不打断创作')
  await expect(page.getByLabel('画面描述', {exact:true})).toHaveValue('A fox crossing the snow.')
  expect((await (await page.request.get('/api/state')).json()).settings).toEqual(initial)

  await trigger.click()
  await expect(idle).toHaveValue(String(initial.idle_minutes))
  expect(await exitSwitch.isChecked()).toBe(initial.stop_on_exit)
  await dialog.getByText('高级连接', {exact:true}).click()
  await expect(identity).toHaveValue(initial.identity)
  await idle.selectOption('30')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('设置已保存', {exact:true})).toBeVisible()
  expect((await (await page.request.get('/api/state')).json()).settings).toEqual({...initial,idle_minutes:30})

  await trigger.click()
  await expect(save).toBeDisabled()
  await page.route('**/api/settings', route => route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({detail:'模拟保存失败'})}))
  await idle.selectOption('60')
  await dialog.getByText('高级连接', {exact:true}).click()
  await identity.fill('/tmp/workbench-test-identity')
  await save.click()
  await expect(dialog.getByRole('alert')).toContainText('模拟保存失败')
  await expect(idle).toHaveValue('60')
  await expect(identity).toHaveValue('/tmp/workbench-test-identity')
  await expect(save).toBeEnabled()
  await page.unroute('**/api/settings')
  // Retry the same edits and keep the dialog open until the request finishes.
  let releaseSave!: () => void
  const pendingSave = new Promise<void>(resolve => { releaseSave = resolve })
  await page.route('**/api/settings', async route => { await pendingSave; await route.continue() })
  await save.click()
  await expect(dialog.getByRole('button', {name:'保存中…',exact:true})).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  releaseSave()
  await expect(dialog).toHaveCount(0)
  await page.unroute('**/api/settings')
  expect((await (await page.request.get('/api/state')).json()).settings).toEqual({...initial,idle_minutes:60,identity:'/tmp/workbench-test-identity'})

  await page.setViewportSize({width:339,height:640})
  await trigger.click()
  await expect(save).toBeInViewport()
  await expect(exitSwitch).toBeInViewport()
  await dialog.getByText('高级连接', {exact:true}).click()
  await expect(identity).toBeInViewport()
  expect(await dialog.locator('.settings-content').evaluate(el => el.scrollHeight <= el.clientHeight + 1 && el.scrollWidth <= el.clientWidth + 1)).toBeTruthy()
  expect(await page.evaluate(() => ({width:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight}))).toEqual({width:339,height:640})
  await dialog.getByRole('button',{name:'切换到 colab3',exact:true}).click()
  await expect(dialog.getByRole('button',{name:'切换到 colab3',exact:true})).toHaveAttribute('aria-pressed','true')
  expect((await (await page.request.get('/api/state')).json()).accounts.find((a: {id:string}) => a.id === 'colab3').machine.session).toBeNull()
  await idle.selectOption('120')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await page.getByRole('button', {name:'算力与性能',exact:true}).click()
  await expect(page.getByLabel('当前账号', {exact:true})).toHaveValue('colab3')
  await page.getByRole('button', {name:'空闲 60m 关闭',exact:true}).click()
  await expect(idle).toHaveValue('60')
  await dialog.getByLabel('关闭弹窗').click()
  await expect(page.getByRole('button', {name:'空闲 60m 关闭',exact:true})).toBeFocused()

  await page.setViewportSize({width:1280,height:720})
  await page.getByLabel('成片与任务', {exact:true}).click()
  await page.getByLabel('搜索作品').fill('保留筛选')
  await trigger.click()
  await expect(dialog).toBeInViewport()
  expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(480)
  await idle.selectOption('120')
  await page.mouse.click(5,5)
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'作品管理',exact:true})).toBeVisible()
  await expect(page.getByLabel('搜索作品')).toHaveValue('保留筛选')
  expect((await (await page.request.get('/api/state')).json()).settings.idle_minutes).toBe(60)
})

