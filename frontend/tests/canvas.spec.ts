import { expect, test, type Page } from '@playwright/test'

const demoState = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fieldwork-canvas-demo-v1')!))
async function openDemo(page: Page) {
  await page.goto('/?view=canvas')
  await expect(page.getByRole('tab', { name: '图片探索', exact: true })).toBeVisible()
  await expect(page.locator('.cd-node')).toHaveCount(3)
  await page.clock.install({ time: new Date('2026-11-13T10:00:00Z') })
  await page.clock.pauseAt(new Date('2026-11-13T10:00:10Z'))
}

test('canvases share queues; defaults affect new work, queued work can move, and instances run in parallel', async ({ page }) => {
  const errors: string[] = [], gpuCalls: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/(jobs$|accounts\/[^/]+\/(start|stop)$|llm\/[^/]+\/start$)/.test(new URL(request.url()).pathname)) gpuCalls.push(request.url()) })
  await openDemo(page)
  await page.getByLabel('暂停排队 G4 · 01', { exact: true }).click()
  await page.getByRole('button', { name: '运行画布', exact: true }).click()
  await expect(page.locator('.cd-task.queued')).toHaveCount(3)
  await page.getByRole('button', { name: '运行画布', exact: true }).click()
  await expect(page.locator('.cd-task.queued')).toHaveCount(3)
  await page.getByRole('tab', { name: '视频分镜', exact: true }).click()
  await page.getByRole('button', { name: '生成 森林漫游', exact: true }).click()
  await expect(page.locator('.cd-task.queued')).toHaveCount(4)
  await expect(page.getByLabel('任务 晨雾', { exact: true })).toContainText('图片探索')
  await page.getByLabel('画布默认实例', { exact: true }).selectOption('demo-g4-2')
  await expect(page.getByLabel('森林漫游 的任务实例', { exact: true })).toHaveValue('demo-g4-1')
  await page.getByRole('button', { name: '生成 湖面涟漪', exact: true }).click()
  await page.clock.fastForward(2400)
  await expect(page.locator('.cd-task.running')).toHaveCount(1)
  await expect(page.getByLabel('任务 湖面涟漪', { exact: true })).toContainText('G4 · 02')
  await page.getByLabel('远山 的任务实例', { exact: true }).selectOption('demo-g4-2')
  await page.getByLabel('继续排队 G4 · 01', { exact: true }).click()
  await page.clock.fastForward(250)
  await expect(page.locator('.cd-task.running')).toHaveCount(2)
  const state = await demoState(page)
  expect(state.tasks).toHaveLength(5)
  expect(state.tasks.filter((task: { status: string }) => task.status === 'running').map((task: { instanceId: string }) => task.instanceId).sort()).toEqual(['demo-g4-1', 'demo-g4-2'])
  expect(state.tasks.find((task: { name: string }) => task.name === '远山').instanceId).toBe('demo-g4-2')
  await expect(page.getByLabel('算力实例 G4 · 01', { exact: true })).toContainText('2 张画布')
  await expect(page.getByLabel('算力实例 G4 · 02', { exact: true })).toContainText('2 张画布')
  await expect(page.getByLabel('关闭 G4 · 01', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '创作工作台', exact: true }).click()
  await page.getByRole('button', { name: '画布', exact: true }).click()
  await expect(page.locator('.cd-task.running')).toHaveCount(2)
  await page.screenshot({ path: '../screenshots/review/canvas-demo-shared-queues.png' })
  expect(gpuCalls).toEqual([])
  expect(errors).toEqual([])
})

test('tasks retain submitted inputs and queues survive refresh; completed nodes retain result versions', async ({ page }) => {
  await openDemo(page)
  await page.getByLabel('暂停排队 G4 · 01', { exact: true }).click()
  await page.getByRole('button', { name: '生成 晨雾', exact: true }).click()
  const original = (await demoState(page)).tasks[0]
  await page.getByRole('button', { name: '设置 晨雾', exact: true }).click()
  await page.getByLabel('节点描述', { exact: true }).fill('下一次生成的新提示词')
  await page.getByLabel('节点随机种子', { exact: true }).fill('42')
  await expect(page.getByLabel('节点执行实例', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByLabel('画布默认实例', { exact: true }).selectOption('demo-g4-2')
  await page.reload()
  await page.clock.resume()
  await expect(page.locator('.cd-task.queued')).toHaveCount(1)
  await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now()) + 1000))
  await expect(page.getByLabel('晨雾 的任务实例', { exact: true })).toHaveValue('demo-g4-1')
  await page.getByLabel('继续排队 G4 · 01', { exact: true }).click()
  await page.clock.fastForward(250)
  await page.clock.fastForward(10000)
  await page.getByRole('button', { name: '历史记录', exact: true }).click()
  await expect(page.locator('.cd-task.done')).toHaveCount(1)
  const state = await demoState(page)
  const node = state.boards[0].nodes[0]
  expect(node.data.prompt).toBe('下一次生成的新提示词')
  expect(node.data.versions[0].prompt).toBe(original.prompt)
  expect(node.data.versions[0].seed).toBe(original.seed)
  await expect(page.getByRole('img', { name: '演示结果示意图', exact: true })).toBeVisible()
})

